# 절 분리 — 문장부호 + 한국어 연결어미(전언절과 1인칭절이 한 문장에 붙어 있는 경우가 흔하다).
# 포럼체 평서형 종결어미(-음/-함/-임/-됨) 뒤의 공백도 문장 경계다 — 마침표를 거의 안 쓰기 때문에
# 이걸 넣지 않으면 "녹아있었음 다른 후기도 그랬다는" 이 한 절로 붙어 전언 가드에 잘못 걸린다.
_CLAUSE_SPLIT_RE = re.compile(
    r"[\n.!?？,·…]+|(?<=고)\s+|(?<=는데)\s+|(?<=은데)\s+|(?<=지만)\s+|(?<=면서)\s+"
    r"|(?<=음)\s+|(?<=함)\s+|(?<=임)\s+|(?<=됨)\s+")


def clauses(text: str) -> list[str]:
    """평가 판정 단위. 빈 조각은 버린다."""
    return [c.strip() for c in _CLAUSE_SPLIT_RE.split(text or "") if c and c.strip()]


def is_meta(text: str) -> bool:
    """M — 갤 메타/드라마/뉴스 위젯."""
    return bool(_M_RE.search(text or ""))


def is_question(text: str) -> bool:
    """Q — 질문·조언요청 화행. 드롭 사유가 아니라 관측·순위용."""
    return bool(_Q_RE.search(text or ""))


def is_hearsay_span(text: str) -> bool:
    """
    이 조각이 '남의 경험'을 가리키는가 — 전언·미사용·비사용근거 표지 중 하나라도 있으면 참.

    두 곳이 같은 판단을 쓴다: `firsthand_clauses`(E 축 절 단위)와
    `extract.drop_hearsay_reviews`(모델이 댄 근거 스니펫 자체 검사).
    한 함수로 묶어 둔 이유는 둘이 갈라지면 게이트와 라벨이 조용히 어긋나기 때문이다.
    """
    t = text or ""
    return bool(_HEARSAY_RE.search(t) or _UNUSED_RE.search(t) or _NONUSE_SRC_RE.search(t))


def has_firsthand_eval(text: str) -> bool:
    """E — '평가어가 있고 전언·미사용 표지가 없는' 절이 하나라도 있는가."""
    return bool(firsthand_clauses(text))


def firsthand_clauses(text: str) -> list[str]:
    """E 의 근거 절 목록(관측성 — verdict 로깅에 쓴다)."""
    if _NONUSE_SRC_RE.search(text or ""):        # 글이 스스로 '안 만져보고 쓴 것'이라고 밝힘
        return []
    return [c for c in clauses(text) if _EVAL_RE.search(c) and not is_hearsay_span(c)]


def is_candidate_span(text: str) -> bool:
    """이 **근거 조각**이 '아직 안 산 것을 고르는 중'을 가리키는가 —
    `extract.drop_hearsay_reviews` 4번째 겹 전용. `is_hearsay_span` 과 같은 층이다.

    **축이 아니다.** M/Q/E 어느 축에도 안 들어가고 `axes()` 도 안 본다 — 추출된 항목의
    `firsthand_evidence` 하나를 검사할 뿐이다. 관련성 게이트가 이 판정으로 조각을 버리면
    첨삭 스레드가 후보에서 사라지는데, 그 스레드엔 **남이 쓴 진짜 후기 댓글**이 달린다.

    ⚠️ 검사 대상은 조각의 **근거 스니펫 자체**이지 글 전체가 아니다. 짧은 평점 나열
      (`잭두콩 썸`)이나 순위(`1믹스 2허밍`)는 **진짜 보유 후기**라 여기 걸리면 안 된다 —
      실측으로 확인된 자리다(스레드 142738 은 `이렇개 만져봤고` 라고 밝힌 보유 평가글이다).
      표지가 없으면 통과시킨다. 어휘 확장 시 반례 확인법은 `LEXICON["purchase_intent"]` 주석.
    """
    return bool(_PURCHASE_INTENT_RE.search(text or ""))


def is_negative(text: str) -> bool:
    """AC8 편향 보존 하드게이트 — 부정 감성이면 E 와 무관하게 후보로 남긴다(드롭 금지)."""
    return bool(_NEGATIVE_RE.search(text or ""))


def axes(text: str) -> dict[str, int]:
    """텍스트 → 절대 축 3개. 배타 아님 — 셋 다 1 일 수도 있다."""
    return {"M": int(is_meta(text)),
            "Q": int(is_question(text)),
            "E": int(has_firsthand_eval(text))}


